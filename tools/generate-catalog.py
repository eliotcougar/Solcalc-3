"""Build/check the ChEBI English catalog and independent localization catalogs."""
from pathlib import Path
import math
import re
import sys
from chebi_catalog import build, localizations, read, save
from import_solubility import SOLVENT_DATA, SOLVENTS

ROOT = Path(__file__).resolve().parents[1]


def valid_cas(value):
    assert re.fullmatch(r'[1-9][0-9]{1,6}-[0-9]{2}-[0-9]', value), value
    digits = value.replace('-', '')
    assert sum(int(c) * i for i, c in enumerate(digits[-2::-1], 1)) % 10 == int(digits[-1]), value


check = '--check' in sys.argv
chebi_index, records, active = build(check, valid_cas)

solubilities = []
identities = {identity: formula for identity, _, formula, *_ in records}
selectable = {identity for identity, *_ in active}
columns = ['chebi_id', 'solvent', 'unit', 'value', 'temperature_c', 'ph', 'density', 'source']
seen = set()
solvent_masses = {r['name']: float(r['molar_mass']) for r in SOLVENT_DATA}
assert len(solvent_masses) == len(SOLVENT_DATA) == len(SOLVENTS)
assert all(math.isfinite(mass) and mass > 0 for mass in solvent_masses.values())
composition_units = {'mass_percent', 'g_100g_solvent', 'mol_kg_solvent', 'mole_fraction'}
qualitative_units = {'insoluble', 'practically_insoluble'}
curated = read(ROOT / 'data/source/solubility.tsv')
curated_keys = {(row['chebi_id'], row['solvent']) for row in curated}
bulk = [row for row in read(ROOT / 'data/source/solubility-reference.tsv')
        if (row['chebi_id'], row['solvent']) not in curated_keys]
for row in curated + bulk:
    assert set(row) == {*columns, 'formula'}, row
    identity = row['chebi_id']
    assert identities.get(f'chebi:{identity}') == row['formula'], row
    solvent = row['solvent']
    assert solvent in solvent_masses, row
    key = (identity, solvent)
    assert key not in seen, row
    seen.add(key)
    unit = row['unit']
    assert unit in composition_units | qualitative_units | {'g_l_solution', 'mol_l_solution'}, row
    value = float(row['value']) if row['value'] else None
    temperature = float(row['temperature_c']) if row['temperature_c'] else None
    assert temperature is None or (math.isfinite(temperature) and temperature > -273.15), row
    if unit in qualitative_units:
        assert value is None, row
    else:
        assert value is not None and math.isfinite(value) and value > 0, row
        assert unit != 'mass_percent' or value < 100, row
        assert unit != 'mole_fraction' or value < 1, row
    ph = float(row['ph']) if row['ph'] else None
    assert ph is None or math.isfinite(ph), row
    density = float(row['density']) if row['density'] else None
    assert density is None or (unit in composition_units
                               and math.isfinite(density) and density > 0), row
    source = row['source']
    assert source.startswith('https://') and source == source.strip(), row
    if f'chebi:{identity}' in selectable:
        solubilities.append((identity, solvent, unit, value, temperature, ph, density, source, solvent_masses[solvent]))
assert solubilities
print(f'Solubility: {len(solubilities)} measurements for {len({row[0] for row in solubilities})} ChEBI substances')
estimated = set()
added_predictions = 0
for row in read(ROOT / 'data/source/solubility-prediction.tsv'):
    assert set(row) == {'chebi_id', 'formula', 'mol_l'}, row
    identity = row['chebi_id']
    assert identities.get(f'chebi:{identity}') == row['formula'], row
    assert identity not in estimated, row
    estimated.add(identity)
    value = float(row['mol_l'])
    assert math.isfinite(value) and value > 0, row
    if f'chebi:{identity}' in selectable and (identity, 'Water') not in seen:
        solubilities.append((identity, 'Water', 'esol_prediction', value, None, None,
                             None, 'https://doi.org/10.1021/ci034243x', solvent_masses['Water']))
        added_predictions += 1
print(f'Solubility: {added_predictions} water predictions for pairs without measurements')
save(ROOT / 'data/bundled/solubility.sqlite',
     'CREATE TABLE solubility(chebi_id TEXT NOT NULL,solvent TEXT NOT NULL,'
     'unit TEXT NOT NULL,value REAL,temperature_c REAL,'
     'ph REAL,density REAL,source TEXT NOT NULL,solvent_molar_mass REAL NOT NULL,PRIMARY KEY(chebi_id,solvent));',
     {'catalog_version': '3'}, 'solubility', [*columns, 'solvent_molar_mass'], sorted(solubilities), check, 0x534F4C53)

index = ['// Generated by tools/generate-catalog.py.',
         'pub const LOCALES: &[(&str, &[u8])] = &[']
for path in sorted((ROOT / 'data/source/locales').glob('*.tsv')):
    code = path.stem
    assert re.fullmatch(r'[a-z]{2,3}(?:-[a-z0-9]{2,8})*', code) and code != 'en', code
    rows = read(path)
    assert rows and all(set(r) == {'substance_id', 'cas', 'formula', 'name', 'synonyms'} for r in rows), path
    assert len({(r['substance_id'], r['cas'], r['formula']) for r in rows}) == len(rows), path
    for row in rows:
        assert row['name'], path
        if row['cas']:
            valid_cas(row['cas'])
        if not row['substance_id']:
            assert row['cas'] and row['formula'], path
    translated, matched = localizations(
        [r for r in rows if r['substance_id'] not in identities or r['substance_id'] in selectable],
        active)
    save(ROOT / f'data/bundled/locales/{code}.sqlite',
         'CREATE TABLE translations(substance_id TEXT PRIMARY KEY,name TEXT NOT NULL,synonyms TEXT NOT NULL);',
         {'locale': code, 'catalog_version': '3'}, 'translations',
         ['substance_id', 'name', 'synonyms'], translated, check, 0x534F4C4C)
    index.append(f'    ("{code}", include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/data/bundled/locales/{code}.sqlite"))),')
    print(f'{code}: {matched}/{len(rows)} source translations matched to {len(translated)} ChEBI entities; '
          f'{len(rows)-matched} unmatched translations retained in source')
index.append('];')
index.extend(chebi_index)
index = '\n'.join(index) + '\n'
index_path = ROOT / 'data/bundled/locale_index.rs'
if check:
    assert index_path.read_text(encoding='utf-8') == index, 'Regenerate locale index'
else:
    index_path.write_text(index, encoding='utf-8', newline='\n')
