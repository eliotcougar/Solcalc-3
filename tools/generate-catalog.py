"""Build/check the ChEBI English catalog and independent localization catalogs."""
from pathlib import Path
import re
import sys
from chebi_catalog import build, localizations, read, save

ROOT = Path(__file__).resolve().parents[1]


def valid_cas(value):
    assert re.fullmatch(r'[1-9][0-9]{1,6}-[0-9]{2}-[0-9]', value), value
    digits = value.replace('-', '')
    assert sum(int(c) * i for i, c in enumerate(digits[-2::-1], 1)) % 10 == int(digits[-1]), value


check = '--check' in sys.argv
chebi_index, records = build(check, valid_cas)
index = ['// Generated by tools/generate-catalog.py.',
         'pub const LOCALES: &[(&str, &[u8])] = &[']
for path in sorted((ROOT / 'data/source/locales').glob('*.tsv')):
    code = path.stem
    assert re.fullmatch(r'[a-z]{2,3}(?:-[a-z0-9]{2,8})*', code) and code != 'en', code
    rows = read(path)
    assert rows and all(set(r) == {'cas', 'formula', 'name', 'synonyms'} for r in rows), path
    assert len({(r['cas'], r['formula']) for r in rows}) == len(rows), path
    for row in rows:
        valid_cas(row['cas'])
        assert row['formula'] and row['name'], path
    translated, matched = localizations(rows, records)
    save(ROOT / f'data/bundled/locales/{code}.sqlite',
         'CREATE TABLE translations(substance_id TEXT PRIMARY KEY,name TEXT NOT NULL,synonyms TEXT NOT NULL);',
         {'locale': code, 'catalog_version': '3'}, 'translations',
         ['substance_id', 'name', 'synonyms'], translated, check, 0x534F4C4C)
    index.append(f'    ("{code}", include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/data/bundled/locales/{code}.sqlite"))),')
    print(f'{code}: {matched}/{len(rows)} source translations matched to {len(translated)} ChEBI entities; '
          f'{len(rows)-matched} unmatched translations retained in source')
index.append('];')
index.extend(chebi_index)
index = '\n'.join(index) + '\n'
index_path = ROOT / 'data/bundled/locale_index.rs'
if check:
    assert index_path.read_text(encoding='utf-8') == index, 'Regenerate locale index'
else:
    index_path.write_text(index, encoding='utf-8', newline='\n')
